"""Render the A1 baseline report -- the Phase 3 go/no-go evidence.

Everything here comes from measured artifacts. The judge-free metrics stand on
their own; the judged ones are labelled as depending on a judge whose agreement
with a human has not yet been established.
"""

from __future__ import annotations

import json
from typing import Any

from ragft.eval.metrics.citation import aggregate as citation_aggregate
from ragft.eval.metrics.format_check import aggregate as format_aggregate
from ragft.eval.metrics.latency import summarise as latency_summarise
from ragft.settings import REPO_ROOT

EVAL_DIR = REPO_ROOT / "data" / "eval"
REPORTS = REPO_ROOT / "reports"


def build() -> dict[str, Any]:
    rows = [
        json.loads(line)
        for line in (EVAL_DIR / "responses" / "A1_base_zeroshot.jsonl").open(encoding="utf-8")
        if line.strip()
    ]
    responses = [r["response"] for r in rows]
    sources = [r["source_section_ids"] for r in rows]

    payload: dict[str, Any] = {
        "arm": "A1_base_zeroshot",
        "n": len(rows),
        "format": format_aggregate(responses),
        "citation": citation_aggregate(responses, sources),
        "latency": latency_summarise(
            [r["latency_seconds"] for r in rows],
            [r["prompt_tokens"] for r in rows],
            [r["completion_tokens"] for r in rows],
        ),
    }

    ans_path = EVAL_DIR / "answerability_summary.json"
    if ans_path.exists():
        payload["answerability"] = json.loads(ans_path.read_text(encoding="utf-8"))

    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "baseline_A1.json").write_text(
        json.dumps(payload, indent=2) + "\n", encoding="utf-8"
    )
    return payload


def render(p: dict[str, Any]) -> str:
    c, f, lat = p["citation"], p["format"], p["latency"]
    ans = p.get("answerability")

    gate = ""
    if ans:
        rate = ans["parametric_answerable_rate"]
        verdict = (
            "**CEILING RISK.** A large share of the gold set is answerable without "
            "retrieval, so every cell of the 2x2 compresses toward ceiling and Phase 4 "
            "training compute buys little."
            if rate > 0.80
            else (
                "**PROCEED.** The base model does not already know enough of the corpus "
                "to compress the grid, so there is room for adaptation to show an effect."
                if rate < 0.60
                else "**MARGINAL.** Enough of the corpus is already known that effect sizes "
                "will be compressed. Proceed, but expect small deltas and read them against "
                "this baseline rather than against zero."
            )
        )
        gate = f"""## Phase 3 gate: parametric answerability

**{rate:.1%}** of gold items are answered correctly by the base model with **no
retrieval at all** (judge: `{ans["judge_model"]}`, {ans["judge_unparseable"]} unparseable).

{verdict}

By stratum: {json.dumps(ans["by_stratum"])}

The same measurement on the OpenStax biology corpus this project began with
returned **75.7%**, and that run was gated MARGINAL: the model already knew the
material, so every cell compressed and adaptation had little room to show
anything. Moving to statutes in force from July 2024 was intended to change
exactly this number, and it did -- **{0.757 - rate:+.1%}** against biology.

This is threat 4 measured rather than assumed, and the decision to spend Phase 4
compute is taken from it rather than after the fact.

"""

    return f"""# Baseline: A1 (base model, no retrieval)

Generated by `ragft.eval.report_baseline`. **Do not hand-edit.**

{p["n"]} gold items over Indian statutes. This arm is the control the other three
are read against -- without it, "RAG beats fine-tuning" has no reference point.

{gate}## Citation grounding -- judge-free

Scored at increasing strictness, because one number hides the finding.

| Level | Rate |
|---|---|
| Produces a citation | {c["parseable_rate"]:.1%} |
| Names an act **in the corpus** | {c["act_exists_rate"]:.1%} |
| Cites a section that **exists** | {c["section_exists_rate"]:.1%} |
| Cites the **correct** section | **{c["section_correct_rate"]:.1%}** |
| **Fabrication** (real section, wrong one) | **{c["fabrication_rate"]:.1%}** |
| **Out-of-corpus act** (repealed pre-2024 law) | **{c["out_of_corpus_act_rate"]:.1%}** |

`out_of_corpus_act` is the signature failure on this corpus. A model trained
before mid-2024 answers from the Indian Penal Code, the Code of Criminal
Procedure or the Indian Evidence Act -- all repealed in 2023. Those citations are
well-formed and were correct law until recently. They are simply no longer the
statutes in force, which is exactly the failure a legal retrieval system exists
to prevent.

## Format adherence -- judge-free

| | Rate |
|---|---|
| Valid (Answer + Why) | {f["valid_rate"]:.1%} |
| Complete (+ Source) | {f["complete_rate"]:.1%} |

Read as a **manipulation check**, not a result. What matters here is that the
base arm complies with the format when given few-shot examples, so a later
"fine-tuning wins on format" claim cannot be an artefact of the baseline never
having been asked (threat 2).

## Latency and cost

| | |
|---|---|
| p50 | {lat["p50_seconds"]}s |
| p95 | {lat["p95_seconds"]}s |
| GPU-seconds/query | {lat["gpu_seconds_per_query"]} |
| Mean prompt tokens | {lat["mean_prompt_tokens"]} |
| Mean completion tokens | {lat["mean_completion_tokens"]} |

GPU contention at measurement: `exclusive={lat["contention"]["exclusive"]}`.
{lat["caveat"]}

## What is NOT here

Judged accuracy is deliberately absent from the headline. The judge is a local
9.6 GB model and its agreement with a human has not been established yet. Until
Cohen's kappa is measured, every number above that needed a judge is
provisional -- and every number that did not is not.
"""


def main() -> None:
    payload = build()
    out = REPORTS / "baseline_A1.md"
    out.write_text(render(payload), encoding="utf-8")
    print(f"Wrote {out}")
    c = payload["citation"]
    print(
        f"  section correct {c['section_correct_rate']:.1%} | page in range "
        f"{c['section_exists_rate']:.1%} | fabrication {c['fabrication_rate']:.1%} "
        f"| out-of-corpus {c['out_of_corpus_act_rate']:.1%}"
    )


if __name__ == "__main__":
    main()
