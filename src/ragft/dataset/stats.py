"""Dataset card: size, cost, rejection rate, and the token-length measurement.

Two jobs. The obvious one is publishing what the dataset actually contains.

The load-bearing one is measuring the token-length distribution of a formatted
training example, because `max_seq_length` should be set from data rather than
guessed. Padding to 2048 when the p99 is 700 wastes most of the compute budget,
and with packing enabled the average example length -- not `seq_len` -- is what
drives the GPU-hour estimate.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from typing import Any

import numpy as np

from ragft.settings import BASE_MODEL, REPO_ROOT

QA_DIR = REPO_ROOT / "data" / "qa"
REPORTS = REPO_ROOT / "reports"


def build_prompt(row: dict[str, Any]) -> str:
    """The exact text a training example occupies, question plus answer."""
    return f"{row['question']}\n\n{row['formatted_answer']}"


def token_lengths(rows: list[dict[str, Any]]) -> dict[str, Any]:
    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained(BASE_MODEL)
    lengths = np.array([len(tok(build_prompt(r))["input_ids"]) for r in rows])
    pcts = {f"p{p}": int(np.percentile(lengths, p)) for p in (50, 75, 90, 95, 99)}

    # Round p99 up to a power of two: attention kernels prefer it, and the
    # rounding costs little when p99 is well under the next boundary.
    p99 = pcts["p99"]
    recommended = next((b for b in (512, 1024, 2048, 4096) if b >= p99), 4096)
    return {
        "tokenizer": BASE_MODEL,
        "n": len(lengths),
        "min": int(lengths.min()),
        "max": int(lengths.max()),
        "mean": round(float(lengths.mean()), 1),
        **pcts,
        "recommended_max_seq_length": recommended,
        "note": (
            "max_seq_length is set from p99 rather than guessed. The mean drives "
            "the GPU-hour projection because packing concatenates short examples "
            "to fill each block."
        ),
    }


def build() -> dict[str, Any]:
    rows = [json.loads(ln) for ln in (QA_DIR / "clean.jsonl").open(encoding="utf-8") if ln.strip()]
    gen = json.loads((QA_DIR / "generation_summary.json").read_text(encoding="utf-8"))
    filt = json.loads((QA_DIR / "filter_summary.json").read_text(encoding="utf-8"))
    decon = json.loads((REPORTS / "decontamination.json").read_text(encoding="utf-8"))

    train = [r for r in rows if r["split"] == "train"]
    tokens = token_lengths(rows)

    card = {
        "generated_at": gen.get("model"),
        "totals": {
            "kept": len(rows),
            "train": len(train),
            "val": sum(r["split"] == "val" for r in rows),
        },
        "by_type": dict(Counter(r["qa_type"] for r in rows).most_common()),
        "by_act": dict(Counter(a for r in rows for a in r["act_slugs"]).most_common()),
        "sections_covered": len({s for r in rows for s in r["source_section_ids"]}),
        "generation": gen,
        "filtering": filt,
        "decontamination_passed": decon["all_passed"],
        "decontamination_enforcement": decon.get("enforcement", {}),
        "token_lengths": tokens,
    }
    (REPORTS / "dataset_card.json").write_text(json.dumps(card, indent=2) + "\n", encoding="utf-8")
    return card


def render(card: dict[str, Any]) -> str:
    t = card["token_lengths"]
    g = card["generation"]
    f = card["filtering"]
    usage = g.get("usage", {})

    rows_by_type = "\n".join(
        f"| {k} | {v:,} | {v / card['totals']['kept']:.1%} |" for k, v in card["by_type"].items()
    )
    rejections = "\n".join(
        f"| `{k}` | {v:,} |" for k, v in f["by_criterion"].items() if k != "kept"
    )

    return f"""# Dataset card

Generated by `ragft.dataset.stats`. **Do not hand-edit.**

Synthetic instruction-tuning data grounded in OpenStax *Biology 1e* and
*Anatomy and Physiology 1e*.

## Licence

Derived from **CC BY 4.0** textbooks. The corpus licence travels with this
dataset and with any model trained on it -- see [`../ATTRIBUTION.md`](../ATTRIBUTION.md).
Code is MIT; this data is not.

## Size

| Split | Pairs |
|---|---|
| train | {card["totals"]["train"]:,} |
| val | {card["totals"]["val"]:,} |
| **total** | **{card["totals"]["kept"]:,}** |

Covering {card["sections_covered"]} distinct corpus sections.

## Composition

The mix was declared in `ragft.dataset.schema.TYPE_MIX` before generation, so
it could not be adjusted after seeing which arm it favoured.

| Type | Count | Share |
|---|---|---|
{rows_by_type}

Two entries pull deliberately in opposite directions. **multihop** favours
fine-tuning, because chunk retrieval is structurally weak at synthesising
across sections. **unanswerable** teaches refusal -- without it, the
fine-tuned arm's hallucination rate would measure this dataset's omission
rather than a property of the method. Dropping either would strawman one side.

## Generation

| | |
|---|---|
| Generator | `{g.get("model")}` |
| Tasks | {g.get("tasks_run", 0):,} |
| Wall clock | {g.get("elapsed_seconds", 0) / 3600:.1f} h |
| Prompt tokens | {usage.get("input_tokens", 0):,} |
| Completion tokens | {usage.get("output_tokens", 0):,} |
| **Cost** | **${usage.get("estimated_usd", 0):.2f}** |

The generator is deliberately **not** Qwen-family. The student model is
Qwen2.5-7B, so a same-family generator would distil its own style into the
fine-tuned arm -- a confound the settings layer refuses to construct.

Generation prompts are published in [`../prompts/generation/`](../prompts/generation/).

## Filtering

Rejection rate **{f["rejection_rate"]:.1%}** ({f["rejected"]:,} of {f["input_rows"]:,}).

| Criterion | Rejected |
|---|---|
{rejections}

`{f["meta_prefix_normalised_fields"]:,}` fields were **normalised** rather than
rejected: the local generator opens explanations with "The passage states
that ..." despite instructions. That prefix strips losslessly, and rejecting it
would have discarded most of the dataset over a stylistic tic. References that
are structurally embedded, and so cannot be removed without changing meaning,
are still rejected under `passage_reference`.

This matters because the fine-tuned model never sees a passage at inference.
Training it on text that refers to one teaches it to cite a source it cannot
read.

## Decontamination

All checks passed: **{card["decontamination_passed"]}**. See
[`decontamination.md`](decontamination.md).

## Token lengths

Measured with the `{t["tokenizer"]}` tokenizer over the full formatted example
(question + three-part answer).

| Percentile | Tokens |
|---|---|
| p50 | {t["p50"]:,} |
| p75 | {t["p75"]:,} |
| p90 | {t["p90"]:,} |
| p95 | {t["p95"]:,} |
| **p99** | **{t["p99"]:,}** |
| max | {t["max"]:,} |
| mean | {t["mean"]:,} |

**`max_seq_length` = {t["recommended_max_seq_length"]}**, set from p99 rather
than guessed. The mean ({t["mean"]:,} tokens) is what drives the GPU-hour
projection, because packing concatenates short examples to fill each block --
using `examples x seq_len` instead overstates the training budget by the
packing ratio.

The project plan assumed ~600 tokens and `max_seq_length` 2048. Both were
wrong, for a structural reason worth stating: a training example is a question
plus a formatted answer and contains **no passage**, because the no-retrieval
arm has to recall parametrically. There is no long context to hold. Padding to
2048 would have wasted roughly {2048 / t["mean"]:.0f}x the compute for nothing.

## Limitations

**The set is small in tokens, not just in rows.** {card["totals"]["train"]:,}
training examples at {t["mean"]:,} tokens is ~{card["totals"]["train"] * t["mean"] / 1000:.0f}k
tokens per epoch. With packing at seq_len {t["recommended_max_seq_length"]} that is
only ~{card["totals"]["train"] * t["mean"] / t["recommended_max_seq_length"]:.0f}
sequences, so an epoch is **~{card["totals"]["train"] * t["mean"] / t["recommended_max_seq_length"] / 8:.0f} optimizer
steps** at effective batch 8, and ~{3 * card["totals"]["train"] * t["mean"] / t["recommended_max_seq_length"] / 8:.0f}
over three epochs.

That is a thin training signal for adapting a 7B model, and no batch size fixes
it -- halving the batch buys steps, not information. It is a real constraint on
how large an effect Phase 4 can be expected to produce, and it is recorded here
rather than discovered later. If the fine-tuned arms show little movement, this
is the first thing to suspect, ahead of any conclusion about fine-tuning as a
method.

**Generator quality bounds everything downstream.** The free local generator
(`{g.get("model")}`) is materially weaker than a hosted model. A stronger
generator is a ~$2 configuration change, not a code change.
"""


def main() -> None:
    argparse.ArgumentParser(description=__doc__).parse_args()
    card = build()
    out = REPORTS / "dataset_card.md"
    out.write_text(render(card), encoding="utf-8")
    print(f"Wrote {out}")
    t = card["token_lengths"]
    print(
        f"  pairs {card['totals']['kept']:,} | p99 {t['p99']} tok "
        f"| mean {t['mean']} | max_seq_length -> {t['recommended_max_seq_length']}"
    )


if __name__ == "__main__":
    main()
